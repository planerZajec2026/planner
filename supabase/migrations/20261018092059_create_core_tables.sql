-- Spec 08, migration 2: core tables.
--
-- Ids of kierunki / grupy / prowadzacy are text: the seed keeps the readable ids the URLs and tests use
-- (`inf-z-3`, `p-zielinski`), new rows get a UUID. These tables stay small (dozens of rows), so random ids are fine.
-- zajecia and przedmioty grow with use and are only referenced internally, so they use identity bigints.

create table public.kierunki (
  id text primary key default gen_random_uuid()::text,
  nazwa text not null,
  created_at timestamptz not null default now(),
  constraint kierunki_nazwa_key unique (nazwa)
);

create table public.grupy (
  id text primary key default gen_random_uuid()::text,
  kod text not null,
  kierunek_id text not null references public.kierunki (id) on delete restrict,
  tryb public.tryb_studiow not null,
  liczba_studentow integer not null default 0,
  created_at timestamptz not null default now(),
  constraint grupy_kod_key unique (kod),
  constraint grupy_liczba_studentow_check check (liczba_studentow >= 0)
);

create index grupy_kierunek_id_idx on public.grupy (kierunek_id);

create table public.prowadzacy (
  id text primary key default gen_random_uuid()::text,
  tytul public.tytul_naukowy not null,
  imie text not null,
  nazwisko text not null,
  instytut text not null default '',
  email text not null,
  zdjecie_url text,
  created_at timestamptz not null default now(),
  constraint prowadzacy_imie_check check (btrim(imie) <> ''),
  constraint prowadzacy_nazwisko_check check (btrim(nazwisko) <> ''),
  constraint prowadzacy_email_check check (email ~ '^[^\s@]+@[^\s@]+\.[^\s@]+$')
);

-- One account per e-mail, ignoring case.
create unique index prowadzacy_email_key on public.prowadzacy (lower(email));

create table public.przedmioty (
  id bigint generated by default as identity primary key,
  nazwa text not null,
  constraint przedmioty_nazwa_key unique (nazwa),
  constraint przedmioty_nazwa_check check (btrim(nazwa) <> '')
);

create table public.prowadzacy_przedmioty (
  prowadzacy_id text not null references public.prowadzacy (id) on delete cascade,
  przedmiot_id bigint not null references public.przedmioty (id) on delete restrict,
  primary key (prowadzacy_id, przedmiot_id)
);

-- The primary key covers lookups by prowadzacy_id; this one covers the other foreign key.
create index prowadzacy_przedmioty_przedmiot_id_idx on public.prowadzacy_przedmioty (przedmiot_id);

-- `do` is a reserved word in SQL, so the hours are godzina_od / godzina_do (the data layer maps them to od / do).
create table public.zajecia (
  id bigint generated by default as identity primary key,
  przedmiot_id bigint not null references public.przedmioty (id) on delete restrict,
  typ public.typ_zajec not null,
  prowadzacy_id text not null references public.prowadzacy (id) on delete restrict,
  grupa_id text not null references public.grupy (id) on delete restrict,
  dzien smallint not null,
  godzina_od time not null,
  godzina_do time not null,
  sala text not null,
  powtarzalnosc public.powtarzalnosc not null default 'co-tydzien',
  created_at timestamptz not null default now(),
  constraint zajecia_dzien_check check (dzien between 1 and 7),
  constraint zajecia_godziny_check check (godzina_od < godzina_do),
  constraint zajecia_sala_check check (btrim(sala) <> '')
);

create index zajecia_grupa_id_idx on public.zajecia (grupa_id);
create index zajecia_prowadzacy_id_idx on public.zajecia (prowadzacy_id);
create index zajecia_przedmiot_id_idx on public.zajecia (przedmiot_id);
