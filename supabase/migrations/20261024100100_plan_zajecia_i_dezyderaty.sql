-- Spec 13, migration 2: what has to be scheduled (`zajecia_plan`) and the constraints around it.

-- One row = one cycle of meetings: always the same plan day, time and room.
create table public.zajecia_plan (
  id text primary key,
  rocznik_id text not null references public.roczniki (id) on delete cascade,
  przedmiot_id text not null references public.przedmioty_plan (id) on delete restrict,
  forma text not null,
  liczba_studentow integer not null,
  laczone_z text,
  dodatkowi_studenci integer not null default 0,
  godziny_programowe integer,
  liczba_spotkan smallint not null,
  sloty_na_spotkanie smallint not null,
  czestotliwosc text not null,
  tydzien_od smallint not null,
  tydzien_do smallint not null,
  typy_sal text[] not null default '{}',
  dozwolone_sale text[] not null default '{}',
  wymagane_wyposazenie text[] not null default '{}',
  tryb text not null,
  powiazanie text,
  typ_powiazania text,
  tygodnie_niedostepne smallint[] not null default '{}',
  uwagi text,
  constraint zajecia_plan_forma_check check (forma in ('W', 'K', 'LI', 'P', 'LEK', 'SEM')),
  constraint zajecia_plan_liczba_studentow_check check (liczba_studentow >= 0 and dodatkowi_studenci >= 0),
  constraint zajecia_plan_liczba_spotkan_check check (liczba_spotkan between 1 and 14),
  constraint zajecia_plan_sloty_check check (sloty_na_spotkanie between 1 and 12),
  constraint zajecia_plan_czestotliwosc_check check (
    czestotliwosc in ('co_tydzien', 'co_2_tygodnie', 'wybrane_tygodnie')
  ),
  constraint zajecia_plan_tygodnie_check check (
    tydzien_od between 1 and 14 and tydzien_do between tydzien_od and 14
  ),
  constraint zajecia_plan_tryb_check check (tryb in ('stacjonarny', 'hybrydowy')),
  constraint zajecia_plan_powiazanie_check check (
    (powiazanie is null) = (typ_powiazania is null)
    and (typ_powiazania is null or typ_powiazania in ('rozne_dni', 'ten_sam_termin'))
  )
);

create index zajecia_plan_rocznik_id_idx on public.zajecia_plan (rocznik_id);
create index zajecia_plan_przedmiot_id_idx on public.zajecia_plan (przedmiot_id);
create index zajecia_plan_powiazanie_idx on public.zajecia_plan (powiazanie) where powiazanie is not null;

-- Groups attending the class (usually one) and its instructors (all of them must be free).
create table public.zajecia_plan_grupy (
  zajecia_id text not null references public.zajecia_plan (id) on delete cascade,
  grupa_id text not null references public.grupy_plan (id) on delete restrict,
  primary key (zajecia_id, grupa_id)
);

create index zajecia_plan_grupy_grupa_id_idx on public.zajecia_plan_grupy (grupa_id);

create table public.zajecia_plan_prowadzacy (
  zajecia_id text not null references public.zajecia_plan (id) on delete cascade,
  prowadzacy_id text not null references public.prowadzacy_plan (id) on delete restrict,
  primary key (zajecia_id, prowadzacy_id)
);

create index zajecia_plan_prowadzacy_prowadzacy_id_idx on public.zajecia_plan_prowadzacy (prowadzacy_id);

-- Fixed slots set outside the faculty (e.g. PE): the group is busy then.
create table public.blokady_stale (
  id bigint generated by default as identity primary key,
  grupa_id text not null references public.grupy_plan (id) on delete cascade,
  dzien smallint not null,
  slot_od smallint not null,
  slot_do smallint not null,
  opis text,
  constraint blokady_stale_dzien_check check (dzien between 1 and 5),
  constraint blokady_stale_sloty_check check (slot_od between 1 and 12 and slot_do between slot_od and 12)
);

create index blokady_stale_grupa_id_idx on public.blokady_stale (grupa_id);

-- Faculty Council and Senate: blocked for instructors with `czlonek_rady_wydzialu`.
create table public.rada_wydzialu (
  id bigint generated by default as identity primary key,
  dzien smallint not null,
  slot_od smallint not null,
  slot_do smallint not null,
  opis text,
  constraint rada_wydzialu_dzien_check check (dzien between 1 and 5),
  constraint rada_wydzialu_sloty_check check (slot_od between 1 and 12 and slot_do between slot_od and 12)
);

-- Desiderata: one row = one hour (day + slot) in which the person cannot teach.
create table public.dezyderaty_terminy (
  prowadzacy_id text not null references public.prowadzacy_plan (id) on delete cascade,
  dzien smallint not null,
  slot smallint not null,
  typ text not null,
  primary key (prowadzacy_id, dzien, slot),
  constraint dezyderaty_terminy_dzien_check check (dzien between 1 and 5),
  constraint dezyderaty_terminy_slot_check check (slot between 1 and 12),
  constraint dezyderaty_terminy_typ_check check (typ in ('wykluczony', 'rada_wydzialu'))
);

create table public.dezyderaty_ogolne (
  prowadzacy_id text primary key references public.prowadzacy_plan (id) on delete cascade,
  liczba_godzin_wykluczonych integer not null default 0,
  powod_wykluczen text,
  preferencja_dni text not null default 'brak',
  inne_uwagi text,
  constraint dezyderaty_ogolne_godziny_check check (liczba_godzin_wykluczonych between 0 and 12),
  constraint dezyderaty_ogolne_preferencja_check check (
    preferencja_dni in ('skumulowane', 'nieskumulowane', 'brak')
  )
);

create table public.dezyderaty_sale (
  id bigint generated by default as identity primary key,
  prowadzacy_id text not null references public.prowadzacy_plan (id) on delete cascade,
  przedmiot text not null,
  forma text,
  rodzaj_sali_nr text,
  sprzet text
);

create index dezyderaty_sale_prowadzacy_id_idx on public.dezyderaty_sale (prowadzacy_id);
