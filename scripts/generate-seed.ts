// Generates supabase/seed.sql from src/lib/mock-data.ts (the real input data of the timetable generator, spec 13), so a
// fresh database starts with the data the generator needs. The seed loads it through `wgraj_dane_planu`, the same
// function the app's import page uses, so there is a single place that maps the data onto the tables.
// Run with `npm run db:seed:generate` after the data changes; CI checks the file is current.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { DANE_PLANU } from "../src/lib/mock-data.ts";

const OUT = fileURLToPath(new URL("../supabase/seed.sql", import.meta.url));

// Dollar quoting: the JSON needs no escaping as long as it never contains the closing tag.
const TAG = "$dane_planu$";
const json = JSON.stringify(DANE_PLANU);
if (json.includes(TAG)) throw new Error(`The data contains ${TAG}; choose another dollar-quote tag.`);

const sql = `-- GENERATED by scripts/generate-seed.ts from src/lib/mock-data.ts. Do not edit by hand:
-- change the source data and run \`npm run db:mock:generate\` and \`npm run db:seed:generate\`.
-- Applied by \`supabase db reset\` (local) and only on request in the cloud (spec 09).

select public.wgraj_dane_planu(${TAG}${json}${TAG}::jsonb);

insert into public.ustawienia (rok_akademicki, semestr) values ('2026/2027', 'zimowy');
`;

writeFileSync(OUT, sql.replaceAll("\r\n", "\n"));
console.log(`Wrote ${OUT}`);
