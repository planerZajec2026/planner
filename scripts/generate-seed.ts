// Generates supabase/seed.sql from src/lib/mock-data.ts, so the database starts with exactly the data the UI and the
// tests expect (same ids). Run with `npm run db:seed:generate` after changing the mock data; CI checks it's current.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { GRUPY, KIERUNKI, PROWADZACY, ZAJECIA } from "../src/lib/mock-data.ts";

const OUT = fileURLToPath(new URL("../supabase/seed.sql", import.meta.url));

/** A SQL literal: strings quoted with '' escaping, numbers as-is, null/undefined as null. */
function lit(value: string | number | null | undefined): string {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number") return String(value);
  return `'${value.replaceAll("'", "''")}'`;
}

function values(rows: (string | number | null | undefined)[][], indent = "  "): string {
  return rows.map((row) => `${indent}(${row.map(lit).join(", ")})`).join(",\n");
}

const przedmioty = [
  ...new Set([...PROWADZACY.flatMap((p) => p.przedmioty), ...ZAJECIA.map((z) => z.przedmiot)]),
].sort((a, b) => a.localeCompare(b, "pl"));

const sql = `-- GENERATED by scripts/generate-seed.ts from src/lib/mock-data.ts. Do not edit by hand:
-- change the mock data and run \`npm run db:seed:generate\`.
-- Applied by \`supabase db reset\` (local) and only on request in the cloud (spec 09).

insert into public.kierunki (id, nazwa) values
${values(KIERUNKI.map((k) => [k.id, k.nazwa]))};

insert into public.grupy (id, kod, kierunek_id, tryb, liczba_studentow) values
${values(GRUPY.map((g) => [g.id, g.kod, g.kierunekId, g.tryb, g.liczbaStudentow]))};

insert into public.prowadzacy (id, tytul, imie, nazwisko, instytut, email, zdjecie_url) values
${values(PROWADZACY.map((p) => [p.id, p.tytul, p.imie, p.nazwisko, p.instytut, p.email, p.zdjecieUrl]))};

insert into public.przedmioty (nazwa) values
${values(przedmioty.map((n) => [n]))};

insert into public.prowadzacy_przedmioty (prowadzacy_id, przedmiot_id)
select v.prowadzacy_id, p.id
from (values
${values(
  PROWADZACY.flatMap((pr) => pr.przedmioty.map((n) => [pr.id, n])),
  "  ",
)}
) as v (prowadzacy_id, nazwa)
join public.przedmioty p on p.nazwa = v.nazwa;

insert into public.zajecia (przedmiot_id, typ, prowadzacy_id, grupa_id, dzien, godzina_od, godzina_do, sala, powtarzalnosc)
select p.id, v.typ::public.typ_zajec, v.prowadzacy_id, v.grupa_id, v.dzien, v.godzina_od::time, v.godzina_do::time,
       v.sala, v.powtarzalnosc::public.powtarzalnosc
from (values
${values(ZAJECIA.map((z) => [z.przedmiot, z.typ, z.prowadzacyId, z.grupaId, z.dzien, z.od, z.do, z.sala, z.powtarzalnosc]))}
) as v (przedmiot, typ, prowadzacy_id, grupa_id, dzien, godzina_od, godzina_do, sala, powtarzalnosc)
join public.przedmioty p on p.nazwa = v.przedmiot;

insert into public.ustawienia (rok_akademicki, semestr) values ('2026/2027', 'zimowy');
`;

writeFileSync(OUT, sql.replaceAll("\r\n", "\n"));
console.log(`Wrote ${OUT}`);
