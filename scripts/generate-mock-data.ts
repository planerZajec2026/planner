// Generates src/lib/mock-data.ts from requirements/dane_planu.json (spec 13): the real input data of the timetable
// generator, as typed constants. mock-data.ts is only the source of the database seed (scripts/generate-seed.ts);
// the app never imports it and reads everything from the database. Run with `npm run db:mock:generate` after the
// source data changes; CI checks the file is current.
//
// The JSON and dane_planu.xlsx hold identical data (src/lib/dane-planu.test.ts compares them table by table).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { podsumuj, sprawdzDanePlanu, TABELE } from "../src/lib/dane-planu.ts";

const SOURCE = fileURLToPath(new URL("../requirements/dane_planu.json", import.meta.url));
const OUT = fileURLToPath(new URL("../src/lib/mock-data.ts", import.meta.url));

const wynik = sprawdzDanePlanu(JSON.parse(readFileSync(SOURCE, "utf8")));
if (!wynik.ok) {
  console.error(`requirements/dane_planu.json jest niepoprawny:\n- ${wynik.bledy.join("\n- ")}`);
  process.exit(1);
}
const dane = wynik.dane;

// One row per line: the file is large, and this keeps diffs readable when the data changes.
const tabele = TABELE.map((tabela) => {
  const wiersze = dane[tabela].map((wiersz) => `    ${JSON.stringify(wiersz)},`).join("\n");
  return `  ${tabela}: [\n${wiersze}\n  ],`;
}).join("\n");

const liczby = Object.entries(podsumuj(dane))
  .map(([tabela, n]) => `${tabela} ${n}`)
  .join(", ");

const ts = `// GENERATED by scripts/generate-mock-data.ts from requirements/dane_planu.json. Do not edit by hand:
// change the source data and run \`npm run db:mock:generate\`.
//
// Input data of the timetable generator (Wydział Fizyki i Informatyki Stosowanej UŁ, Informatyka, studia stacjonarne,
// semestr zimowy 2026/27). The only consumer is scripts/generate-seed.ts, which turns it into supabase/seed.sql;
// the app reads the data from the database (eslint forbids importing this file from src/).
// Rows: ${liczby}.
import type { DanePlanu } from "./dane-planu";

export const DANE_PLANU: DanePlanu = {
${tabele}
};
`;

writeFileSync(OUT, ts.replaceAll("\r\n", "\n"));
console.log(`Wrote ${OUT} (${liczby})`);
