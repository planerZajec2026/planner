// Writes .env.local for the local Supabase stack (`npm run db:start`): the API URL plus the publishable and service_role
// keys. The local stack signs its keys with the Supabase CLI's well-known development secret, so they can be derived
// without asking the CLI (whose `status` omits them when optional services are excluded, as in CI).
//
//   npm run db:env           writes .env.local unless it exists
//   npm run db:env -- --force   overwrites it
//
// These keys only work against the local stack. Never use them, or this script, for a cloud project.
import { createHmac } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";

const SECRET = "super-secret-jwt-token-with-at-least-32-characters-long";
const URL = "http://127.0.0.1:54321";
const FILE = ".env.local";

const base64url = (value) => Buffer.from(JSON.stringify(value)).toString("base64url");

function key(role) {
  const header = base64url({ alg: "HS256", typ: "JWT" });
  const payload = base64url({ iss: "supabase-demo", role, exp: 1983812996 });
  const signature = createHmac("sha256", SECRET).update(`${header}.${payload}`).digest("base64url");
  return `${header}.${payload}.${signature}`;
}

if (existsSync(FILE) && !process.argv.includes("--force")) {
  console.log(`${FILE} already exists; leaving it alone (pass --force to overwrite).`);
} else {
  writeFileSync(
    FILE,
    [
      "# Local Supabase (generated by `npm run db:env`). Never commit.",
      `NEXT_PUBLIC_SUPABASE_URL=${URL}`,
      `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${key("anon")}`,
      `SUPABASE_SERVICE_ROLE_KEY=${key("service_role")}`,
      "",
    ].join("\n"),
  );
  console.log(`Wrote ${FILE} for the local Supabase at ${URL}.`);
}
